--- מחזיר טקסט לפי פנייה ומחליף {name}
function T.F(s, gender, name)
	if s == nil then
		return ""
	end
	local out
	if typeof(s) == "table" then
		out = (gender == "f") and s.f or s.m
	else
		out = s
	end
	if name then
		out = string.gsub(out, "{name}", name)
	end
	return out
end

